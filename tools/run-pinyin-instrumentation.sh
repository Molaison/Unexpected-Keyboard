#!/usr/bin/env bash
# Run on a disposable emulator. Builds are performed separately by Gradle.
set -euo pipefail
: "${ANDROID_HOME:?Set ANDROID_HOME to the Android SDK}"
pinyin_serial="${1:?Usage: run-pinyin-instrumentation.sh EMULATOR_SERIAL}"
pinyin_root="$(cd "$(dirname "$0")/.." && pwd)"
mkdir -p "$pinyin_root/build/validation"
pinyin_adb="$ANDROID_HOME/platform-tools/adb"
pinyin_package=com.molaison.unexpectedkeyboard.doubao
pinyin_ime="$pinyin_package/juloo.keyboard2.Keyboard2"
"$pinyin_adb" -s "$pinyin_serial" shell input keyevent KEYCODE_WAKEUP
"$pinyin_adb" -s "$pinyin_serial" shell wm dismiss-keyguard
"$pinyin_adb" -s "$pinyin_serial" install -r "$pinyin_root/build/outputs/apk/debug/Unexpected-Keyboard-debug.apk"
"$pinyin_adb" -s "$pinyin_serial" install -r "$pinyin_root/build/outputs/apk/androidTest/debug/Unexpected-Keyboard-debug-androidTest.apk"
pinyin_previous_ime="$("$pinyin_adb" -s "$pinyin_serial" shell settings get secure default_input_method | tr -d '\r')"
restore_ime() {
  pinyin_status=$?
  for screenshot in pinyin-keyboard pinyin-nine-key pinyin-candidates-expanded pinyin-font-1 pinyin-font-2 emoji-panel clipboard-light clipboard-dark nine-key-light nine-key-dark clipboard-undo failure-ux ui-zh-idle-nine ui-zh-idle-qwerty ui-zh-numbers ui-zh-symbols ui-zh-clipboard ui-zh-emoji; do
    if "$pinyin_adb" -s "$pinyin_serial" exec-out run-as "$pinyin_package" cat "cache/$screenshot.png" \
        > "$pinyin_root/build/validation/$screenshot.png.tmp" 2>/dev/null; then
      # Some adb versions report success even when run-as cat prints an error.
      # Retain only real PNGs, never a missing-file diagnostic with a .png suffix.
      if [[ "$(od -An -tx1 -N8 "$pinyin_root/build/validation/$screenshot.png.tmp" | tr -d ' \n')" == 89504e470d0a1a0a ]]; then
        mv "$pinyin_root/build/validation/$screenshot.png.tmp" "$pinyin_root/build/validation/$screenshot.png"
      else
        rm -f "$pinyin_root/build/validation/$screenshot.png.tmp"
      fi
    else
      rm -f "$pinyin_root/build/validation/$screenshot.png.tmp"
    fi
  done
  "$pinyin_adb" -s "$pinyin_serial" logcat -d -v threadtime > "$pinyin_root/build/validation/logcat.txt" || true
  "$pinyin_adb" -s "$pinyin_serial" shell dumpsys input_method > "$pinyin_root/build/validation/input-method.txt" || true
  "$pinyin_adb" -s "$pinyin_serial" shell dumpsys window > "$pinyin_root/build/validation/window.txt" || true
  "$pinyin_adb" -s "$pinyin_serial" exec-out screencap -p > "$pinyin_root/build/validation/final-screen.png" || true
  if [[ -n "$pinyin_previous_ime" && "$pinyin_previous_ime" != null ]]; then
    "$pinyin_adb" -s "$pinyin_serial" shell ime set "$pinyin_previous_ime" || true
  fi
  return "$pinyin_status"
}
# Each invocation owns a fresh evidence set, including on a reused emulator.
# Remove only the named screenshots generated by this harness.
for screenshot in pinyin-keyboard pinyin-nine-key pinyin-candidates-expanded pinyin-font-1 pinyin-font-2 emoji-panel clipboard-light clipboard-dark nine-key-light nine-key-dark clipboard-undo failure-ux ui-zh-idle-nine ui-zh-idle-qwerty ui-zh-numbers ui-zh-symbols ui-zh-clipboard ui-zh-emoji; do
  "$pinyin_adb" -s "$pinyin_serial" shell run-as "$pinyin_package" rm -f "cache/$screenshot.png"
  rm -f "$pinyin_root/build/validation/$screenshot.png" "$pinyin_root/build/validation/$screenshot.png.tmp"
done
trap restore_ime EXIT
"$pinyin_adb" -s "$pinyin_serial" shell ime enable "$pinyin_ime"
# Instrumentation restarts this app process. Select the IME inside the runner,
# after that restart, rather than starting it and immediately killing it here.
"$pinyin_adb" -s "$pinyin_serial" shell am instrument -w -r \
  "$pinyin_package.test/juloo.keyboard2.PinyinSmokeTest" | tee "$pinyin_root/build/validation/instrumentation.log"
grep -q 'PINYIN_SMOKE_OK' "$pinyin_root/build/validation/instrumentation.log"
grep -q '^INSTRUMENTATION_CODE: -1' "$pinyin_root/build/validation/instrumentation.log"

# This suite uses only fake WebSockets and local EditTexts. Never enable the
# separate voice_live/voice_microphone modes in credential-free PR CI.
"$pinyin_adb" -s "$pinyin_serial" shell am instrument -w -r \
  -e voice_regression true \
  "$pinyin_package.test/juloo.keyboard2.PinyinSmokeTest" | tee "$pinyin_root/build/validation/doubao-regression.log"
grep -q 'DOUBAO_REGRESSION_OK' "$pinyin_root/build/validation/doubao-regression.log"
grep -q '^INSTRUMENTATION_CODE: -1' "$pinyin_root/build/validation/doubao-regression.log"
# Focused Chinese-locale UI evidence. Reuses the debug editor fixture and the
# real application-locale API; it must not repeat the voice/cloud suites.
"$pinyin_adb" -s "$pinyin_serial" shell am instrument -w -r \
  -e ui_zh true \
  "$pinyin_package.test/juloo.keyboard2.PinyinSmokeTest" | tee "$pinyin_root/build/validation/ui-zh.log"
grep -q 'UI_ZH_OK' "$pinyin_root/build/validation/ui-zh.log"
grep -q '^INSTRUMENTATION_CODE: -1' "$pinyin_root/build/validation/ui-zh.log"
# Pull the focused evidence now, before validating it. The EXIT trap also
# collects failure evidence and logcat (including the CORE/METRICS records).
for screenshot in ui-zh-idle-nine ui-zh-idle-qwerty ui-zh-numbers ui-zh-symbols ui-zh-clipboard ui-zh-emoji; do
  pinyin_zh_png="$pinyin_root/build/validation/$screenshot.png"
  "$pinyin_adb" -s "$pinyin_serial" exec-out run-as "$pinyin_package" cat "cache/$screenshot.png" > "$pinyin_zh_png.tmp"
  [[ "$(od -An -tx1 -N8 "$pinyin_zh_png.tmp" | tr -d ' \n')" == 89504e470d0a1a0a ]] \
    || { echo "$screenshot.png is not a PNG"; exit 1; }
  mv "$pinyin_zh_png.tmp" "$pinyin_zh_png"
done
